"""The parity matrix's index. The rows live in docs/parity/*.md, one file per area, so the people building different
areas edit different files. This script checks every row and writes docs/parity.md: the legend and a count of rows by
status per area. `--check` fails if the index is stale, a row is malformed, or a `done` / `stricter here` row names a test
that does not exist; `--done` also fails if a row is
still `planned`. Run it before every commit that changes behaviour."""
from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TESTS = re.compile(r"\btest_\w+")
HEADER = "| Original guarantee (file:line) | Where it lives here | How it's checked (test name) | Status |"
STATUS = re.compile(r"^(done|stricter here|planned|not ported, because )(?:\b|(?<= )).*$")

INTRO = """# Parity matrix

This is the contract. Each row is one guarantee the original, [ai-job-search](https://github.com/MadsLorentzen/ai-job-search)
(v1.7.2 plus 65 commits), makes, derived from its command specs, skills, tools and tests rather than from memory, with the
place it lives here and the test that pins it. The rows are in [docs/parity/](parity/), one file per area; this index is
generated by `python tools/parity.py`. **Every commit that adds behaviour updates its rows. Done means no row says `planned`.**

Status is one of `done`, `planned`, `stricter here` (the rebuild enforces in code what the original only said in prose),
or `not ported, because ...`. `planned (stricter: ...)` is planned and will be stricter than the original.

"""


def rows(path: Path) -> list[tuple[int, list[str]]]:
    out = []
    for n, line in enumerate(path.read_text().splitlines(), 1):
        if line.startswith("| ") and not line.startswith("| ---") and line.strip() != HEADER:
            out.append((n, [c.strip() for c in re.split(r"(?<!\\)\|", line.strip())[1:-1]]))
    return out


def defined_tests() -> set[str]:
    return {m for f in (ROOT / "tests").rglob("*.py") for m in re.findall(r"^\s*(?:async )?def (test_\w+)", f.read_text(), re.M)}


def build() -> tuple[str, list[str], int]:
    problems, planned, lines, tests = [], 0, [], defined_tests()
    for path in sorted((ROOT / "docs" / "parity").glob("*.md")):
        counts = Counter()
        for n, cells in rows(path):
            if len(cells) != 4 or not all(cells):
                problems.append(f"{path.name}:{n}: a row needs four non-empty cells, found {len(cells)}")
                continue
            kind = next((k for k in ("done", "stricter here", "planned", "not ported") if cells[3].startswith(k)), cells[3])
            if not STATUS.match(cells[3]):
                problems.append(f"{path.name}:{n}: bad status {cells[3]!r}")
            elif kind in ("done", "stricter here"):
                named = TESTS.findall(cells[2])
                missing = [t for t in named if t not in tests]
                if not named or missing:
                    problems.append(f"{path.name}:{n}: a `{kind}` row must name tests that exist" + (f"; missing {missing}" if missing else ""))
            counts[kind] += 1
        planned += counts["planned"]
        lines.append(f"| [{path.stem}](parity/{path.name}) | {sum(counts.values())} | {counts['done']} | {counts['stricter here']} | "
                     f"{counts['not ported']} | {counts['planned']} |")
    table = "| Area | Rows | done | stricter here | not ported | planned |\n|---|---|---|---|---|---|\n" + "\n".join(lines) + "\n"
    return INTRO + table, problems, planned


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true")
    p.add_argument("--done", action="store_true", help="also fail if any row is still planned")
    args = p.parse_args()
    text, problems, planned = build()
    target = ROOT / "docs" / "parity.md"
    if args.check:
        if not target.exists() or target.read_text() != text:
            problems.append("docs/parity.md is stale: run `python tools/parity.py`")
        if args.done and planned:
            problems.append(f"{planned} rows are still planned")
    else:
        target.write_text(text)
    for problem in problems:
        print(problem, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
